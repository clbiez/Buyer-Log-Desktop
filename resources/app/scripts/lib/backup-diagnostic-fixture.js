'use strict';

const fs = require('node:fs');
const fsp = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const defaults = require('../../tests/fixtures/backup-crc-sha-v1.json');
const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');

async function fileHash(file) {
  const hash = crypto.createHash('sha256');
  for await (const chunk of fs.createReadStream(file)) hash.update(chunk);
  return hash.digest('hex');
}
async function createFixture(root, overrides = {}) {
  const config = { ...defaults, ...overrides };
  for (const key of ['diskFiles', 'diskBytes', 'bufferBytes', 'chunkBytes']) {
    assert.ok(Number.isSafeInteger(config[key]) && config[key] > 0, `invalid fixture ${key}`);
  }
  assert.ok(config.diskFiles <= 32 && config.diskBytes <= 128 * 1024 * 1024 && config.bufferBytes <= 64 * 1024 * 1024 && config.chunkBytes <= 1024 * 1024, 'fixture budget exceeded');
  // Only generated bytes; no option to ingest an existing source directory.
  const source = path.join(root, 'generated-source'); await fsp.mkdir(source);
  const entries = [], expected = [];
  for (let i = 0; i < config.diskFiles; i++) {
    const chunk = Buffer.alloc(config.chunkBytes);
    for (let j = 0; j < chunk.length; j++) chunk[j] = (j * 31 + i * 17 + config.seed) & 255;
    const sourcePath = path.join(source, `disk-${i}.bin`), handle = await fsp.open(sourcePath, 'wx');
    const hash = crypto.createHash('sha256');
    try {
      let left = config.diskBytes;
      while (left) { const bytes = chunk.subarray(0, Math.min(left, chunk.length)); await handle.writeFile(bytes); hash.update(bytes); left -= bytes.length; }
    } finally { await handle.close(); }
    const name = `system/local-data/disk-${i}.bin`;
    entries.push({ name, sourcePath, stage: 'data' });
    expected.push({ path: name, size: config.diskBytes, sha256: hash.digest('hex'), stage: 'data' });
  }
  for (const [name, buffer, stage] of [
    ['system/local-data/empty.bin', Buffer.alloc(0), 'data'],
    ['system/local-data/vector.txt', Buffer.from('123456789'), 'data'],
    ['system/config/synthetic-settings.bin', Buffer.alloc(config.bufferBytes, 97), 'settings'],
  ]) {
    entries.push({ name, buffer, stage }); expected.push({ path: name, size: buffer.length, sha256: sha256(buffer), stage });
  }
  const manifest = { app_version: '7.0.339', created_at: config.createdAt, backup_type: 'full', user: { id: 'synthetic-admin01' }, device: { hostname: 'synthetic', platform: 'fixture', arch: 'fixture' }, scope_schema: 1, scope_components: ['full-system'] };
  const fixtureSha256 = sha256(JSON.stringify({ config, expected, manifest }));
  return { config, entries, expected, manifest, fixtureSha256 };
}
async function verifyRestored(root, expected) {
  for (const item of expected) {
    const file = path.join(root, ...item.path.split('/'));
    assert.equal((await fsp.stat(file)).size, item.size, item.path);
    assert.equal(await fileHash(file), item.sha256, item.path);
  }
}
module.exports = { createFixture, verifyRestored, fileHash, sha256 };
